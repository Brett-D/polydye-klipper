def block_gcode(layers=6, config=None, brim=False, top=False, obj="cube", band=1.6, feed=12000, colour_from=0,
                neighbour=False):
    """Orca-like G-code: a 10 x 10 mm block at X 95-105, Y 95-105, 0.2 mm layers. Each layer: white lines (T0) along X
    at `feed` mm/min filling Y 95+band to 105, then coloured ones (T1, from layer `colour_from` on; white before)
    filling its -Y band; with `top` the last layer's coloured lines are top surface; with `brim` a 3 mm brim on the
    first layer; with `neighbour` a white object "wall" touching it at X 85-95, printed first."""
    cfg = dict(CONFIG, **(config or {}))
    g = ["; HEADER_BLOCK_START", "; generated by OrcaSlicer 2.5.0-beta", "; HEADER_BLOCK_END", "",
         "; EXECUTABLE_BLOCK_START"]
    if obj:
        g.append("EXCLUDE_OBJECT_DEFINE NAME=%s CENTER=100,100" % (obj,))
    g += [";TYPE:Custom", "START_PRINT BED_TEMP=60 EXTRUDER_TEMP=210", "G90", "M83", "T0"]

    def lines(ys, x0=95.2, x1=104.8):
        for k, y in enumerate(ys):
            a, b = (x0, x1) if k % 2 == 0 else (x1, x0)
            g.append("G1 X%.3f Y%.3f F%d" % (a, y, feed))
            g.append("G1 X%.3f Y%.3f E.5" % (b, y))
    for n in range(layers):
        z = 0.2 * (n + 1)
        g += [";LAYER_CHANGE", ";Z:%g" % (z,), ";HEIGHT:0.2", "G1 E-.8 F2100", "G1 Z%g" % (z,)]
        if neighbour:
            g += ["EXCLUDE_OBJECT_START NAME=wall", ";TYPE:Sparse infill", ";WIDTH:0.42"]
            lines([95.2 + 0.4 * k for k in range(25)], 85.2, 94.8)
            g.append("EXCLUDE_OBJECT_END NAME=wall")
        if obj:
            g.append("EXCLUDE_OBJECT_START NAME=%s" % (obj,))
        if n == 0 and brim:
            g += [";TYPE:Brim", ";WIDTH:0.5"]
            for k in range(6):
                d = 0.25 + 0.5 * k
                g.append("G1 X%.3f Y%.3f" % (95 - d, 95 - d))
                for x, y in ((105 + d, 95 - d), (105 + d, 105 + d), (95 - d, 105 + d), (95 - d, 95 - d)):
                    g.append("G1 X%.3f Y%.3f E.5" % (x, y))
        g += [";TYPE:Sparse infill", ";WIDTH:0.42"]
        lines([95 + band + 0.2 + 0.4 * k for k in range(int(round((10 - band) / 0.4)))])
        g += ["G1 E-.8 F2100", "; filament end gcode", "T%d" % (n >= colour_from,),
              "M104 S210 ; set nozzle temperature",
              "; filament start gcode", ";TYPE:%s" % ("Top surface" if top and n == layers - 1 else "Outer wall",),
              ";WIDTH:0.42", "G1 E.8 F2400"]
        lines([95.2 + 0.4 * k for k in range(int(round(band / 0.4)))])
        g += ["G1 E-.8 F2100", "T0", "M104 S210 ; set nozzle temperature"]
        if obj:
            g.append("EXCLUDE_OBJECT_END NAME=%s" % (obj,))
    g += [";TYPE:Custom", "; filament end gcode", "END_PRINT", "; EXECUTABLE_BLOCK_END", "", "; CONFIG_BLOCK_START"]
    g += ["; %s = %s" % kv for kv in cfg.items()]
    g += ["; CONFIG_BLOCK_END", "", "; filament used [mm] = 1.0, 1.0"]
    return [line + "\n" for line in g]


def part_gcode(layers, config=None):
    """Orca-like G-code of an object "part", 0.2 mm layers: layers[n] is a list of (tool, ;TYPE:, paths[, height]),
    each path a list of (x, y) points extruded in one go, 0.42 mm wide and `height` (0.2) high."""
    g = ["; HEADER_BLOCK_START", "; generated by OrcaSlicer 2.5.0-beta", "; HEADER_BLOCK_END", "",
         "; EXECUTABLE_BLOCK_START", "EXCLUDE_OBJECT_DEFINE NAME=part CENTER=100,100", ";TYPE:Custom",
         "START_PRINT BED_TEMP=60 EXTRUDER_TEMP=210", "G90", "M83", "T0"]
    tool = 0
    for n, spec in enumerate(layers):
        z = 0.2 * (n + 1)
        g += [";LAYER_CHANGE", ";Z:%g" % (z,), ";HEIGHT:0.2", "G1 Z%g" % (z,), "EXCLUDE_OBJECT_START NAME=part"]
        for t, kind, paths, *height in spec:
            if t != tool:
                g.append("T%d" % (t,))
                tool = t
            g += [";TYPE:%s" % (kind,), ";WIDTH:0.42", ";HEIGHT:%g" % (height[0] if height else 0.2,)]
            for path in paths:
                g.append("G1 X%.3f Y%.3f F12000" % path[0])
                g += ["G1 X%.3f Y%.3f E.1" % p for p in path[1:]]
        g.append("EXCLUDE_OBJECT_END NAME=part")
    g += [";TYPE:Custom", "END_PRINT", "; EXECUTABLE_BLOCK_END", "", "; CONFIG_BLOCK_START"]
    g += ["; %s = %s" % kv for kv in dict(CONFIG, **(config or {})).items()]
    g += ["; CONFIG_BLOCK_END", "", "; filament used [mm] = 1.0, 1.0"]
    return [line + "\n" for line in g]


def square(a, b):
    """A square loop from (a, a) to (b, b)."""
    return [(a, a), (b, a), (b, b), (a, b), (a, a)]


def walls(tool, count, first=0):
    """`count` wall loops of the 10 mm block at X, Y 95-105, from loop `first` (0: the outer wall) inwards."""
    return [(tool, "Outer wall" if k == 0 else "Inner wall", [square(95.2 + 0.4 * k, 104.8 - 0.4 * k)])
            for k in range(first, first + count)]


def xlines(x0, x1, ys):
    return [[(x0, y), (x1, y)] for y in ys]


def run(lines, *args):
    opts = post.options(list(args) + ["x.gcode"])
    return post.process(lines, opts)


def job_dots(out, registration=(0, 0, 0, 0)):
    """Every dot of the job in `out` (the post-processed lines) as the add-on prints it, with `registration`:
    [(record, colour, nozzle position, bed X, bed Y, length of its run along the pass)]."""
    with tempfile.NamedTemporaryFile("w", suffix=".gcode", delete=False) as f:
        f.writelines(out)
    try:
        header, records = polydye.job_load(f.name)
        dots = []
        with open(f.name, "rb") as fb:
            for rec in records:
                data, columns, first = polydye.job_pass_data(polydye.job_record_data(fb, rec), rec['colours'],
                                                             rec['columns'], rec['dir'], registration)
                cols = [data[i * 42:(i + 1) * 42] for i in range(columns)]
                for c in range(3):
                    for p in range(112):
                        byte, bit = polydye.COLOR_BYTE_ORDER[c][p % 14] + 14 * c, p // 14
                        fired = [col[byte] >> bit & 1 for col in cols]
                        k = 0
                        while k < columns:
                            if not fired[k]:
                                k += 1
                                continue
                            run_end = k
                            while run_end < columns and fired[run_end]:
                                run_end += 1
                            for i in range(k, run_end):
                                drawing = first + i * rec['dir']
                                dots.append((rec, c, p, rec['x'] + (50 - p) * SX, rec['y'] + drawing * PITCH,
                                             run_end - k))
                            k = run_end
        return header, records, dots
    finally:
        os.unlink(f.name)


@unittest.skipIf(post.np is None, "needs numpy")
class Structure(unittest.TestCase):
    def test_tool_changes_go_and_each_layer_is_inked_after_its_last_extrusion(self):
        src = block_gcode(layers=3)
        out, summary = run(src)
        text = "".join(out)
        self.assertNotRegex(text, r"(?m)^T\d")
        self.assertIn("PolyDye ink job: ", summary)
        # POLYDYE_JOB first, before the start G-code heats anything.
        self.assertEqual(out[out.index("; EXECUTABLE_BLOCK_START\n") + 2], "POLYDYE_JOB\n")
        # Each layer's ink right after its last extrusion (the last coloured line), before its retraction.
        blocks = [n for n, line in enumerate(out) if line.startswith("; PolyDye ink: layer ")]
        self.assertEqual(len(blocks), 3)
        for layer, n in enumerate(blocks):
            self.assertRegex(out[n - 1], r"^G1 X[\d.]+ Y96\.400 E\.5$")
            self.assertEqual(out[n], "; PolyDye ink: layer %d (Z %.3f), %d passes\n" % (
                layer, 0.2 * (layer + 1), len(re.findall(r"POLYDYE_JOB_PASS N=\d+ ; layer %d " % (layer,), text))))
        self.assertEqual(text.count("POLYDYE_PRIME"), 1)
        self.assertIn("POLYDYE_ENABLE LIVE=1\nPOLYDYE_PRIME ;", text.split("; PolyDye ink: layer 1")[0])
        block = text.split("; PolyDye ink: layer 2")[1].split(";TYPE:Custom")[0].split("\n")[1:]
        x, y = re.match(r"G1 X([\d.]+) Y([\d.]+) E", out[blocks[-1] - 1]).groups()
        # Gentler moves while the ink prints (POLYDYE_INK_MOTION), the limits put back right after it.
        self.assertEqual(block[:8], ["EXCLUDE_OBJECT_END NAME=cube", "SAVE_GCODE_STATE NAME=polydye_ink", "G90", "M83",
                                     "G1 E-1.50 F2700", "G1 Z1.600 F600", "POLYDYE_INK_MOTION ACCEL=1000 SCV=1",
                                     "POLYDYE_ENABLE LIVE=1"])
        passes = [ln for ln in block if ln.startswith("POLYDYE_JOB_PASS")]
        self.assertTrue(passes)
        self.assertEqual(block[8 + len(passes):], [
            "M400", "POLYDYE_ENABLE LIVE=0", "POLYDYE_INK_MOTION RESTORE=1", "G4 P5000",
            "G1 X%.3f Y%.3f F9000" % (float(x), float(y)),
            "G1 Z0.600 F600", "G1 E1.50 F2400", "RESTORE_GCODE_STATE NAME=polydye_ink",
            "EXCLUDE_OBJECT_START NAME=cube", "POLYDYE_JOB_END", "G1 E-.8 F2100",
            "M104 S210 ; set nozzle temperature", "EXCLUDE_OBJECT_END NAME=cube", ""])
        # The passes are numbered in printing order, and the job sits after the print, before the config block.
        numbers = [int(n) for n in re.findall(r"POLYDYE_JOB_PASS N=(\d+)", text)]
        self.assertEqual(numbers, list(range(len(numbers))))
        tail = text.split("; EXECUTABLE_BLOCK_END\n")[1]
        self.assertTrue(tail.lstrip().startswith("; POLYDYE_JOB_BEGIN\n;PDJ version=2 dpi=847 nozzle_dpi=300 "
                                                 "pass_axis=y positions=28-82 passes=%d layers=3 " % (len(numbers),)))
        # --ink-accel 0: the print's own motion limits.
        out, _ = run(src, "--ink-accel", "0")
        self.assertNotIn("POLYDYE_INK_MOTION", "".join(out))
        self.assertTrue(tail.endswith("; filament used [mm] = 1.0, 1.0\n"))
        self.assertLess(tail.index("; POLYDYE_JOB_END"), tail.index("; CONFIG_BLOCK_START"))

    def test_the_job_says_how_high_and_how_slow_its_ink_goes(self):
        # The ink 1 mm (--gap) above the top inked layer (Z 0.6); the acceleration the G-code sets (none: 0); the
        # bursts' length.
        out, _ = run(block_gcode(layers=3), "--ink-accel", "0")
        self.assertIn(" ink_accel=0 ink_z=1.600 prewarm_s=6 ", "".join(out))
        src = block_gcode(layers=3)
        src.insert(src.index("G90\n"), "SET_VELOCITY_LIMIT ACCEL=1500\n")
        out, _ = run(src, "--gap", "2", "--prewarm", "0", "--ink-accel", "0")
        self.assertIn(" ink_accel=1500 ink_z=2.600 prewarm_s=0 ", "".join(out))
        # POLYDYE_INK_MOTION's 1000 (by default) is the lowest then; a lower one the G-code sets stays the lowest.
        out, _ = run(src)
        self.assertIn(" ink_accel=1000 ", "".join(out))
        src[src.index("SET_VELOCITY_LIMIT ACCEL=1500\n")] = "SET_VELOCITY_LIMIT ACCEL=600\n"
        out, _ = run(src)
        self.assertIn(" ink_accel=600 ", "".join(out))

    def test_relative_moves_make_e_relative(self):
        # G91 makes E relative too, even after M82 (as Klipper): both moves extrude.
        layers = post.parse([";LAYER_CHANGE\n", ";Z:0.2\n", "M82\n", "G92 E0\n", "G91\n", "G1 X5 E0.5\n",
                             "G1 Y5 E0.5\n", "G90\n", "G1 X20 E1.5\n", "G1 X30 E1.5\n"])[0]
        self.assertEqual([s[3:7] for s in layers[0].segs], [(0., 0., 5., 0.), (5., 0., 5., 5.), (5., 5., 20., 5.)])

    def test_directions_alternate_unless_one_direction(self):
        out, _ = run(block_gcode(layers=2, band=4.), "--edge-margin", "0")
        dirs = [int(d) for d in re.findall(r"POLYDYE_JOB_PASS N=\d+ ; layer 1 .* DIR=(-?1)", "".join(out))]
        self.assertGreater(len(dirs), 1)
        self.assertEqual(dirs, [1 if k % 2 == 0 else -1 for k in range(len(dirs))])
        out, _ = run(block_gcode(layers=2, band=4.), "--edge-margin", "0", "--one-direction", "--dry-run")
        text = "".join(out)
        self.assertEqual(set(re.findall(r"DIR=(-?1)", text)), {"1"})
        self.assertNotIn("LIVE=1", text)
        self.assertNotIn("POLYDYE_PRIME", text)
        self.assertNotIn("POLYDYE_PREWARM", text)

    def test_nothing_to_ink_leaves_the_gcode_alone(self):
        src = block_gcode(config={'filament_colour': '#FFFFFF;#FFFFFF'})
        out, why = run(src)
        self.assertIsNone(out)
        self.assertIn("no coloured filament", why)
        path = tempfile.mktemp(suffix=".gcode")
        with open(path, "w") as f:
            f.writelines(src)
        try:
            self.assertEqual(post.main([path]), 0)
            with open(path) as f:
                self.assertEqual(f.readlines(), src)
        finally:
            os.unlink(path)

    def test_refusals_leave_the_file_unchanged(self):
        for config, extra, error in (
                ({'enable_prime_tower': '1'}, None, "turn off the prime tower"),
                ({'change_filament_gcode': 'M600'}, None, "clear Change filament G-code"),
                ({'nozzle_temperature': '210,220'}, None, "nozzle_temperature differ"),
                ({'print_sequence': 'by object'}, None, "Print sequence to By layer"),
                ({'spiral_mode': '1'}, None, "spiral vase"),
                ({}, "G2 X100 Y100 I1 J0 E.5", "turn off Arc fitting"),
                ({}, "; POLYDYE_JOB_BEGIN", "already has a PolyDye ink job")):
            src = block_gcode(config=config)
            if extra:
                src.insert(src.index("END_PRINT\n"), extra + "\n")
            with self.assertRaisesRegex(post.PostError, error):
                run(src)
            path = tempfile.mktemp(suffix=".gcode")
            with open(path, "w") as f:
                f.writelines(src)
            try:
                self.assertEqual(post.main([path]), 1)
                with open(path) as f:
                    self.assertEqual(f.readlines(), src)
            finally:
                os.unlink(path)


@unittest.skipIf(post.np is None, "needs numpy")
class Ink(unittest.TestCase):
    def test_ink_is_on_the_coloured_lines_and_off_the_edge(self):
        # Magenta filament: magenta dots only, on the coloured band (Y 95-96.6), never within the 0.5 mm edge margin
        # of the block's outline (no brim: nothing below but the block).
        out, _ = run(block_gcode(layers=4))
        header, records, dots = job_dots(out)
        self.assertTrue(dots)
        self.assertEqual({c for _, c, _, _, _, _ in dots}, {polydye.MAGENTA})
        xs, ys = [d[3] for d in dots], [d[4] for d in dots]
        self.assertGreaterEqual(min(xs), 95.5)
        self.assertLessEqual(max(xs), 104.5)
        self.assertGreaterEqual(min(ys), 95.5)
        self.assertLessEqual(max(ys), 96.61 + PITCH)
        # With a brim under it the edge is safe: the ink reaches the block's edge.
        out, _ = run(block_gcode(layers=4, brim=True))
        _, _, dots = job_dots(out)
        self.assertLess(min(d[4] for d in dots), 95.1)
        self.assertLess(min(d[3] for d in dots), 95.1)

    def test_another_objects_plastic_doesnt_back_the_ink(self):
        # A white object touching the block's -X side could be excluded before it prints: the block's ink still keeps
        # --edge-margin (0.5 mm) from its own edge there, as at its other edges.
        out, _ = run(block_gcode(layers=4, neighbour=True))
        _, records, dots = job_dots(out)
        self.assertEqual({r['object'] for r in records}, {"cube"})
        self.assertGreater(min(d[3] for d in dots), 95.4)
        # Plastic outside any object (a brim Orca prints for the whole plate) can't be excluded: it backs the ink.
        src = block_gcode(layers=4, brim=True)
        start = src.index(";TYPE:Brim\n")
        end = next(n for n in range(start, len(src)) if src[n].startswith(";TYPE:Sparse"))
        brim = src[start:end]
        del src[start:end]
        src[src.index("EXCLUDE_OBJECT_START NAME=cube\n"):src.index("EXCLUDE_OBJECT_START NAME=cube\n")] = brim
        out, _ = run(src)
        _, _, dots = job_dots(out)
        self.assertLess(min(d[3] for d in dots), 95.15)

    def test_no_ink_beyond_the_models_surface(self):
        # With a brim below, the plastic reaches past the block's surface (X, Y 94.99, its outer lines' edges): the
        # ink still stops --inset (0.05 mm) inside it, and reaches it with --inset 0; 0.2 keeps it 0.2 mm in.
        for args, inside in (((), 0.05), (("--inset", "0"), 0.), (("--inset", "0.2"), 0.2)):
            out, _ = run(block_gcode(layers=4, brim=True), *args)
            _, _, dots = job_dots(out)
            xs, ys = [d[3] for d in dots], [d[4] for d in dots]
            edge = 94.99 + inside
            self.assertTrue(edge <= min(xs) < edge + 0.12 and edge <= min(ys) < edge + 0.12, (args, min(xs), min(ys)))
            self.assertTrue(200. - edge - 0.12 < max(xs) <= 200. - edge, (args, max(xs)))

    def test_every_fire_is_at_least_two_columns(self):
        # Whatever the registration moves (an odd number of columns too) and in both directions.
        out, _ = run(block_gcode(layers=3, band=4., config={'filament_colour': '#FFFFFF;#4060A0'}), "--edge-margin",
                     "0")
        for registration in ((0, 0, 0, 0), (-34, 1, 27, -1)):
            _, records, dots = job_dots(out, registration)
            self.assertEqual({r['dir'] for r in records}, {1, -1})
            self.assertEqual({c for _, c, _, _, _, _ in dots}, {0, 1, 2})
            self.assertGreaterEqual(min(d[5] for d in dots), 2)

    def test_coverage_follows_the_colour_and_the_ink_limit(self):
        # #FF00FF: no cyan or yellow, magenta at the ink limit: every dot by default (100 %, solid), half the dots at
        # 50 %, a quarter at 25 %.
        for limit, share in (("100", 1.), ("50", 0.5), ("25", 0.25)):
            out, _ = run(block_gcode(layers=1, band=4., top=True), "--edge-margin", "0", "--inset", "0",
                         "--ink-limit", limit)
            _, records, dots = job_dots(out)
            # The band: 9.6 mm lines 0.4 mm apart filling 4 mm, plus the lines' half widths all round.
            area = (9.6 + 0.42) * (4. + 0.02) / (SX * PITCH)
            self.assertAlmostEqual(len(dots) / area, share, delta=0.03)
        # So light the dither fires nothing: nothing to ink, the G-code unchanged.
        src = block_gcode(layers=1, band=4., top=True)
        self.assertIsNone(run(src, "--ink-limit", "0.5")[0])

    def test_top_surfaces_get_their_coats(self):
        out, _ = run(block_gcode(layers=2, top=True), "--edge-margin", "0")
        self.assertEqual(set(int(c) for c in re.findall(r"; layer 1 pass \d+, coat (\d)", "".join(out))), {1})
        out, _ = run(block_gcode(layers=2, top=True), "--edge-margin", "0", "--top-coats", "2")
        text = "".join(out)
        self.assertEqual(set(int(c) for c in re.findall(r"; layer 1 pass \d+, coat (\d)", text)), {1, 2})
        self.assertEqual(set(int(c) for c in re.findall(r"; layer 0 pass \d+, coat (\d)", text)), {1})
        out, _ = run(block_gcode(layers=2, top=True), "--edge-margin", "0", "--top-coats", "3")
        self.assertEqual(set(int(c) for c in re.findall(r"; layer 1 pass \d+, coat (\d)", "".join(out))), {1, 2, 3})

    def test_partial_tones_are_an_ordered_dither(self):
        # #BFBFBF: a quarter of each ink. The colours fire on different cells (pairs of columns, nozzle positions),
        # each spread evenly: in every 8 x 8 block of cells, 16.
        out, _ = run(block_gcode(layers=1, band=4., config={'filament_colour': '#FFFFFF;#BFBFBF'}),
                     "--edge-margin", "0")
        _, records, dots = job_dots(out)
        cells = [set((r['n'], round((y - r['y']) / PITCH) // 2, p) for r, c, p, x, y, _ in dots if c == ch)
                 for ch in range(3)]
        self.assertTrue(all(cells))
        self.assertFalse(cells[0] & cells[1] or cells[0] & cells[2] or cells[1] & cells[2])
        # Any 8 x 8 block of a period-8 matrix has each threshold once: inside the ink, 48 cells of 64 fire, 16 each.
        blocks = {}
        for ch in range(3):
            for n, row, p in cells[ch]:
                blocks.setdefault((n, row // 8, p // 8), [0, 0, 0])[ch] += 1
        inside = [v for v in blocks.values() if sum(v) == 48]
        self.assertGreater(len(inside), 10)
        self.assertEqual({tuple(v) for v in inside}, {(16, 16, 16)})

    def test_passes_name_their_object(self):
        out, _ = run(block_gcode(layers=1, band=4.), "--edge-margin", "0")
        _, records, _ = job_dots(out)
        self.assertEqual({r['object'] for r in records}, {"cube"})
        out, _ = run(block_gcode(layers=1, band=4., obj=None), "--edge-margin", "0")
        self.assertNotIn("EXCLUDE_OBJECT", "".join(out))
        _, records, _ = job_dots(out)
        self.assertEqual({r['object'] for r in records}, {"-"})

    def test_swaths_tile_the_nozzle_grid(self):
        # Sweeps over 55 positions (28-82), overlapping by 6 (--feather 6); with --feather 0 side by side, the next
        # starting one pitch past the last one's.
        for args, step in (((), 49.), (("--feather", "0"), 55.)):
            out, _ = run(block_gcode(layers=1, band=4.), "--edge-margin", "0", *args)
            _, records, _ = job_dots(out)
            xs = sorted(r['x'] for r in records)
            self.assertGreater(len(xs), 1)
            for a, b in zip(xs, xs[1:]):
                self.assertAlmostEqual((b - a) / SX, step, places=2)

    def test_sweeps_cover_the_footprint_with_the_grid_shifted_per_layer(self):
        # The same footprint every layer: the fewest sweeps that cover it, their grid shifted differently each layer
        # (the golden ratio's multiples over the spare positions), so the seams don't stack up the wall.
        out, _ = run(block_gcode(layers=8, band=4.), "--edge-margin", "0", "--inset", "0")
        _, records, dots = job_dots(out)
        firsts = {}
        for r in records:
            firsts.setdefault(r['layer'], []).append(r['x'])
        self.assertEqual({len(v) for v in firsts.values()}, {3})  # 9.6 + 0.42 mm over 49-position steps
        offsets = [round((min(v) - 94.) / SX) for _, v in sorted(firsts.items())]
        self.assertGreater(len(set(offsets)), 5, offsets)
        self.assertEqual(post.swaths(10, 129, 55, 1, 0.), [10, 64, 118])  # 120 columns: 3 sweeps, 43 to spare
        self.assertEqual(post.swaths(10, 129, 55, 1, 0.999), [-33, 21, 75])
        # Every layer's ink is all there, each dot once, wherever the seams fall.
        per_layer = {}
        for r, c, p, x, y, _ in dots:
            per_layer.setdefault(r['layer'], []).append((c, round(x / SX), round(y / PITCH)))
        self.assertEqual({len(v) for v in per_layer.values()}, {len(set(per_layer[0]))})
        self.assertEqual({len(v) - len(set(v)) for v in per_layer.values()}, {0})

    def test_feathered_joins_share_the_band_once(self):
        # Magenta at 100 % (one ink: 2 + 2 per packet, so nothing is capped): with the joins feathered over 6
        # positions, each dot prints exactly once, the same dots as with the sweeps side by side; in each band the
        # cells go from one sweep to the next along a ramp, a whole cell (two column pairs) to one sweep.
        src = block_gcode(layers=1, band=4.)
        feathered, _ = run(src, "--edge-margin", "0", "--inset", "0")
        plain, _ = run(src, "--edge-margin", "0", "--inset", "0", "--feather", "0")
        _, records, dots = job_dots(feathered)
        got = [(c, round(x / SX), round(y / PITCH)) for _, c, _, x, y, _ in dots]
        self.assertEqual(len(got), len(set(got)))
        self.assertEqual(set(got), {(c, round(x / SX), round(y / PITCH)) for _, c, _, x, y, _ in job_dots(plain)[2]})
        self.assertEqual(len(records), 3)
        xs = sorted(r['x'] for r in records)
        by_dot = {}
        for r, c, p, x, y, run_length in dots:
            self.assertGreaterEqual(run_length, 2)
            by_dot[(round(x / SX), round(y / PITCH))] = r['x']
        # A sweep's share changes only on cell boundaries: every four columns, the same phase in every band column.
        changes = {(y + 1) % 4 for (g, y), o in by_dot.items() if by_dot.get((g, y + 1), o) != o}
        self.assertEqual(len(changes), 1)
        phase = changes.pop()
        owners = {}
        for (g, y), o in by_dot.items():
            owners.setdefault((g, (y - phase) // 4), set()).add(o)
        self.assertEqual({len(v) for v in owners.values()}, {1})
        # The band between the first two sweeps, 6 positions wide: the second's share rises across it.
        band = sorted({g for (g, q), o in owners.items() if xs[0] in o} & {g for (g, q), o in owners.items()
                                                                                   if xs[1] in o})
        self.assertEqual(len(band), 6)
        shares = [sum(xs[1] in o for (g, q), o in owners.items() if g == b)
                  / float(sum(g == b for g, q in owners)) for b in band]
        self.assertLess(shares[0], 0.3)
        self.assertGreater(shares[-1], 0.7)


@unittest.skipIf(post.np is None, "needs numpy")
class Depth(unittest.TestCase):
    """--depth: ink only near the model's surface, beside, above or below, however deep Orca's colour goes."""

    ARGS = ("--edge-margin", "0", "--inset", "0")

    def dots_by_layer(self, src, *args):
        out, _ = run(src, *(self.ARGS + args))
        layers = {}
        for r, c, p, x, y, _ in job_dots(out)[2]:
            layers.setdefault(r['layer'], set()).add((round(x, 3), round(y, 3)))
        return layers

    @staticmethod
    def side(x, y):
        """How far (x, y) is inside the 10 mm block's sides."""
        return min(x - 95., 105. - x, y - 95., 105. - y)

    def test_walls_are_inked_only_near_the_surface_not_near_the_infills_gaps(self):
        # A 2 mm coloured shell (5 wall loops) around white sparse infill with 1.6 mm gaps reaching the shell, 8
        # layers. Mid-height (layers 3, 4: over 0.5 mm from the bottom and top) only the outer 0.5 mm is inked; the
        # gaps are inside the model, not a surface. Layers 0, 1, 6 and 7 are within 0.5 mm of the bottom or top: all of
        # the shell.
        infill = (0, "Sparse infill", xlines(97., 103., (97.3, 99.3, 101.3, 102.7)))
        src = part_gcode([walls(1, 5) + [infill]] * 8)
        full, near = self.dots_by_layer(src), self.dots_by_layer(src, "--depth", "0.5")
        for n in (0, 1, 6, 7):
            self.assertEqual(near[n], full[n], n)
        for n in (3, 4):
            self.assertGreater(max(self.side(*d) for d in full[n]), 1.8)
            self.assertLess(max(self.side(*d) for d in near[n]), 0.6)
            self.assertEqual(near[n], set(d for d in full[n] if self.side(*d) < 0.4) | near[n], n)

    def test_a_hole_in_the_model_is_a_surface(self):
        # A ring: 4 coloured loops round the outside, 4 round a 3.6 mm square hole (98.2-101.8), nothing else. Its
        # middle layers are inked within 0.5 mm of the outside and of the hole's wall, not between.
        hole = [(1, "Outer wall" if k == 0 else "Inner wall", [square(98. - 0.4 * k, 102. + 0.4 * k)])
                for k in range(4)]
        src = part_gcode([walls(1, 4) + hole] * 8)

        def to_hole(x, y):
            dx, dy = max(98.2 - x, 0., x - 101.8), max(98.2 - y, 0., y - 101.8)
            return math.hypot(dx, dy)
        full, near = self.dots_by_layer(src)[4], self.dots_by_layer(src, "--depth", "0.5")[4]
        self.assertGreater(max(min(self.side(*d), to_hole(*d)) for d in full), 1.)
        self.assertLess(max(min(self.side(*d), to_hole(*d)) for d in near), 0.6)
        self.assertLessEqual(set(d for d in full if min(self.side(*d), to_hole(*d)) < 0.4), near)
        self.assertLess(min(to_hole(*d) for d in near), 0.1)

    def test_a_flat_top_is_inked_from_above_and_its_skin_isnt_taken_for_a_bottom(self):
        # Two coloured walls round white sparse infill for 5 layers, then 3 coloured solid layers, the last a top
        # surface. With --depth 0.4 the top two (0.1 and 0.3 mm under the top, from their middles) are inked all
        # over; the one below (0.5) only near the sides: the sparse infill under it is no bottom surface.
        sparse = (0, "Sparse infill", xlines(96., 104., (96.5, 98.5, 100.5, 102.5, 103.5)))
        solid = [(1, kind, xlines(96., 104., [96. + 0.4 * k for k in range(21)])) for kind in
                 ("Internal solid infill", "Internal solid infill", "Top surface")]
        src = part_gcode([walls(1, 2) + [sparse]] * 5 + [walls(1, 2) + [s] for s in solid])
        full, near = self.dots_by_layer(src), self.dots_by_layer(src, "--depth", "0.4")
        self.assertEqual((near[6], near[7]), (full[6], full[7]))
        self.assertGreater(min(self.side(*d) for d in full[5] if self.side(*d) > 4.), 4.)
        self.assertLess(max(self.side(*d) for d in near[5]), 0.5)
        self.assertTrue(near[5])
        # Exactly --depth under the top (the middle of layer 5 is 0.5 mm under it) is within it, also with Orca's
        # ;HEIGHT:0.200001.
        noisy = [line.replace(";HEIGHT:0.2\n", ";HEIGHT:0.200001\n") for line in src]
        self.assertEqual(self.dots_by_layer(noisy, "--depth", "0.5")[5], full[5])
        self.assertEqual(self.dots_by_layer(src, "--depth", "0.3")[6], full[6])  # 1.6 - 1.3 is 0.30000000000000027

    def test_combined_infill_is_plastic_in_the_layers_it_spans_whatever_the_order(self):
        # Orca's infill combination: the sparse infill 0.4 mm high every other layer, between 0.2 mm walls. The layer
        # height is the walls' 0.2 mm whichever comes first in the layer (layer 7's middle is 0.5 mm under the top: all
        # of it inked); the layers between, with no infill of their own, are solid where the infill above reaches
        # down, not a hole inside the walls.
        infill = (0, "Sparse infill", xlines(97., 103., (97.3, 99.3, 101.3, 102.7)), 0.4)
        results = []
        for infill_first in (False, True):
            src = part_gcode([([infill] if n % 2 and infill_first else []) + walls(1, 5) +
                              ([infill] if n % 2 and not infill_first else []) for n in range(10)])
            full, near = self.dots_by_layer(src), self.dots_by_layer(src, "--depth", "0.5")
            self.assertEqual(near[7], full[7])
            for n in (4, 5):
                self.assertGreater(max(self.side(*d) for d in full[n]), 1.8)
                self.assertLess(max(self.side(*d) for d in near[n]), 0.6, (infill_first, n))
            results.append(near)
        self.assertEqual(results[0], results[1])

    def test_depth_must_not_be_negative_and_off_changes_nothing(self):
        src = part_gcode([walls(1, 5)] * 3)
        self.assertEqual(run(src, *self.ARGS)[0], run(src, *(self.ARGS + ("--depth", "0")))[0])
        with self.assertRaises(SystemExit):
            post.options(["--depth", "-0.1", "x.gcode"])


def ink_blocks(out):
    """The ink blocks of post-processed lines: [[line, ...]] from '; PolyDye ink:' to RESTORE_GCODE_STATE."""
    blocks, cur = [], None
    for line in out:
        if line.startswith("; PolyDye ink: layer"):
            cur = []
            blocks.append(cur)
        if cur is not None:
            cur.append(line.strip())
            if line.startswith("RESTORE_GCODE_STATE"):
                cur = None
    return blocks


def with_line(lines, after, new):
    """`lines` with `new` after the first line starting with `after`."""
    k = next(n for n, line in enumerate(lines) if line.startswith(after))
    return lines[:k + 1] + [new + "\n"] + lines[k + 1:]


