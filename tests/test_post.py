PITCH = 25.4 / 847
SX = 25.4 / 300
CONFIG = {'filament_colour': '#FFFFFF;#FF00FF', 'enable_prime_tower': '0', 'change_filament_gcode': '',
          'nozzle_temperature': '210,210', 'filament_diameter': '1.75,1.75'}


def block_gcode(layers=6, config=None, brim=False, top=False, obj="cube", band=1.6, feed=12000, colour_from=0):
    """Orca-like G-code: a 10 x 10 mm block at X 95-105, Y 95-105, 0.2 mm layers. Each layer: white lines (T0) along X
    at `feed` mm/min filling Y 95+band to 105, then coloured ones (T1, from layer `colour_from` on; white before)
    filling its -Y band; with `top` the last layer's coloured lines are top surface; with `brim` a 3 mm brim on the
    first layer."""
    cfg = dict(CONFIG, **(config or {}))
    g = ["; HEADER_BLOCK_START", "; generated by OrcaSlicer 2.5.0-beta", "; HEADER_BLOCK_END", "",
         "; EXECUTABLE_BLOCK_START"]
    if obj:
        g.append("EXCLUDE_OBJECT_DEFINE NAME=%s CENTER=100,100" % (obj,))
    g += [";TYPE:Custom", "START_PRINT BED_TEMP=60 EXTRUDER_TEMP=210", "G90", "M83", "T0"]

    def lines(ys, x0=95.2, x1=104.8):
        for k, y in enumerate(ys):
            a, b = (x0, x1) if k % 2 == 0 else (x1, x0)
            g.append("G1 X%.3f Y%.3f F%d" % (a, y, feed))
            g.append("G1 X%.3f Y%.3f E.5" % (b, y))
    for n in range(layers):
        z = 0.2 * (n + 1)
        g += [";LAYER_CHANGE", ";Z:%g" % (z,), ";HEIGHT:0.2", "G1 E-.8 F2100", "G1 Z%g" % (z,)]
        if obj:
            g.append("EXCLUDE_OBJECT_START NAME=%s" % (obj,))
        if n == 0 and brim:
            g += [";TYPE:Brim", ";WIDTH:0.5"]
            for k in range(6):
                d = 0.25 + 0.5 * k
                g.append("G1 X%.3f Y%.3f" % (95 - d, 95 - d))
                for x, y in ((105 + d, 95 - d), (105 + d, 105 + d), (95 - d, 105 + d), (95 - d, 95 - d)):
                    g.append("G1 X%.3f Y%.3f E.5" % (x, y))
        g += [";TYPE:Sparse infill", ";WIDTH:0.42"]
        lines([95 + band + 0.2 + 0.4 * k for k in range(int(round((10 - band) / 0.4)))])
        g += ["G1 E-.8 F2100", "; filament end gcode", "T%d" % (n >= colour_from,),
              "M104 S210 ; set nozzle temperature",
              "; filament start gcode", ";TYPE:%s" % ("Top surface" if top and n == layers - 1 else "Outer wall",),
              ";WIDTH:0.42", "G1 E.8 F2400"]
        lines([95.2 + 0.4 * k for k in range(int(round(band / 0.4)))])
        g += ["G1 E-.8 F2100", "T0", "M104 S210 ; set nozzle temperature"]
        if obj:
            g.append("EXCLUDE_OBJECT_END NAME=%s" % (obj,))
    g += [";TYPE:Custom", "; filament end gcode", "END_PRINT", "; EXECUTABLE_BLOCK_END", "", "; CONFIG_BLOCK_START"]
    g += ["; %s = %s" % kv for kv in cfg.items()]
    g += ["; CONFIG_BLOCK_END", "", "; filament used [mm] = 1.0, 1.0"]
    return [line + "\n" for line in g]


def run(lines, *args):
    opts = post.options(list(args) + ["x.gcode"])
    return post.process(lines, opts)


def job_dots(out, registration=(0, 0, 0, 0)):
    """Every dot of the job in `out` (the post-processed lines) as the add-on prints it, with `registration`:
    [(record, colour, nozzle position, bed X, bed Y, length of its run along the pass)]."""
    with tempfile.NamedTemporaryFile("w", suffix=".gcode", delete=False) as f:
        f.writelines(out)
    try:
        header, records = polydye.job_load(f.name)
        dots = []
        with open(f.name, "rb") as fb:
            for rec in records:
                data, columns, first = polydye.job_pass_data(polydye.job_record_data(fb, rec), rec['colours'],
                                                             rec['columns'], rec['dir'], registration)
                cols = [data[i * 42:(i + 1) * 42] for i in range(columns)]
                for c in range(3):
                    for p in range(112):
                        byte, bit = polydye.COLOR_BYTE_ORDER[c][p % 14] + 14 * c, p // 14
                        fired = [col[byte] >> bit & 1 for col in cols]
                        k = 0
                        while k < columns:
                            if not fired[k]:
                                k += 1
                                continue
                            run_end = k
                            while run_end < columns and fired[run_end]:
                                run_end += 1
                            for i in range(k, run_end):
                                drawing = first + i * rec['dir']
                                dots.append((rec, c, p, rec['x'] + (50 - p) * SX, rec['y'] + drawing * PITCH,
                                             run_end - k))
                            k = run_end
        return header, records, dots
    finally:
        os.unlink(f.name)


@unittest.skipIf(post.np is None, "needs numpy")
class Structure(unittest.TestCase):
    def test_tool_changes_go_and_each_layer_is_inked_after_its_last_extrusion(self):
        src = block_gcode(layers=3)
        out, summary = run(src)
        text = "".join(out)
        self.assertNotRegex(text, r"(?m)^T\d")
        self.assertIn("PolyDye ink job: ", summary)
        # POLYDYE_JOB first, before the start G-code heats anything.
        self.assertEqual(out[out.index("; EXECUTABLE_BLOCK_START\n") + 2], "POLYDYE_JOB\n")
        # Each layer's ink right after its last extrusion (the last coloured line), before its retraction.
        blocks = [n for n, line in enumerate(out) if line.startswith("; PolyDye ink: layer ")]
        self.assertEqual(len(blocks), 3)
        for layer, n in enumerate(blocks):
            self.assertRegex(out[n - 1], r"^G1 X[\d.]+ Y96\.400 E\.5$")
            self.assertEqual(out[n], "; PolyDye ink: layer %d (Z %.3f), %d passes\n" % (
                layer, 0.2 * (layer + 1), len(re.findall(r"POLYDYE_JOB_PASS N=\d+ ; layer %d " % (layer,), text))))
        self.assertEqual(text.count("POLYDYE_PRIME"), 1)
        self.assertIn("POLYDYE_ENABLE LIVE=1\nPOLYDYE_PRIME ;", text.split("; PolyDye ink: layer 1")[0])
        block = text.split("; PolyDye ink: layer 2")[1].split(";TYPE:Custom")[0].split("\n")[1:]
        x, y = re.match(r"G1 X([\d.]+) Y([\d.]+) E", out[blocks[-1] - 1]).groups()
        self.assertEqual(block[:7], ["EXCLUDE_OBJECT_END NAME=cube", "SAVE_GCODE_STATE NAME=polydye_ink", "G90", "M83",
                                     "G1 E-1.50 F2700", "G1 Z1.600 F600", "POLYDYE_ENABLE LIVE=1"])
        passes = [ln for ln in block if ln.startswith("POLYDYE_JOB_PASS")]
        self.assertTrue(passes)
        self.assertEqual(block[7 + len(passes):], [
            "M400", "POLYDYE_ENABLE LIVE=0", "G4 P5000", "G1 X%.3f Y%.3f F9000" % (float(x), float(y)),
            "G1 Z0.600 F600", "G1 E1.50 F2400", "RESTORE_GCODE_STATE NAME=polydye_ink",
            "EXCLUDE_OBJECT_START NAME=cube", "POLYDYE_JOB_END", "G1 E-.8 F2100",
            "M104 S210 ; set nozzle temperature", "EXCLUDE_OBJECT_END NAME=cube", ""])
        # The passes are numbered in printing order, and the job sits after the print, before the config block.
        numbers = [int(n) for n in re.findall(r"POLYDYE_JOB_PASS N=(\d+)", text)]
        self.assertEqual(numbers, list(range(len(numbers))))
        tail = text.split("; EXECUTABLE_BLOCK_END\n")[1]
        self.assertTrue(tail.lstrip().startswith("; POLYDYE_JOB_BEGIN\n;PDJ version=1 dpi=847 nozzle_dpi=300 "
                                                 "pass_axis=y positions=16-83 passes=%d layers=3 " % (len(numbers),)))
        self.assertTrue(tail.endswith("; filament used [mm] = 1.0, 1.0\n"))
        self.assertLess(tail.index("; POLYDYE_JOB_END"), tail.index("; CONFIG_BLOCK_START"))

    def test_directions_alternate_unless_one_direction(self):
        out, _ = run(block_gcode(layers=2, band=4.), "--edge-margin", "0")
        dirs = [int(d) for d in re.findall(r"POLYDYE_JOB_PASS N=\d+ ; layer 1 .* DIR=(-?1)", "".join(out))]
        self.assertGreater(len(dirs), 1)
        self.assertEqual(dirs, [1 if k % 2 == 0 else -1 for k in range(len(dirs))])
        out, _ = run(block_gcode(layers=2, band=4.), "--edge-margin", "0", "--one-direction", "--dry-run")
        text = "".join(out)
        self.assertEqual(set(re.findall(r"DIR=(-?1)", text)), {"1"})
        self.assertNotIn("LIVE=1", text)
        self.assertNotIn("POLYDYE_PRIME", text)
        self.assertNotIn("POLYDYE_PREWARM", text)

    def test_nothing_to_ink_leaves_the_gcode_alone(self):
        src = block_gcode(config={'filament_colour': '#FFFFFF;#FFFFFF'})
        out, why = run(src)
        self.assertIsNone(out)
        self.assertIn("no coloured filament", why)
        path = tempfile.mktemp(suffix=".gcode")
        with open(path, "w") as f:
            f.writelines(src)
        try:
            self.assertEqual(post.main([path]), 0)
            with open(path) as f:
                self.assertEqual(f.readlines(), src)
        finally:
            os.unlink(path)

    def test_refusals_leave_the_file_unchanged(self):
        for config, extra, error in (
                ({'enable_prime_tower': '1'}, None, "turn off the prime tower"),
                ({'change_filament_gcode': 'M600'}, None, "clear Change filament G-code"),
                ({'nozzle_temperature': '210,220'}, None, "nozzle_temperature differ"),
                ({'print_sequence': 'by object'}, None, "Print sequence to By layer"),
                ({'spiral_mode': '1'}, None, "spiral vase"),
                ({}, "G2 X100 Y100 I1 J0 E.5", "turn off Arc fitting"),
                ({}, "; POLYDYE_JOB_BEGIN", "already has a PolyDye ink job")):
            src = block_gcode(config=config)
            if extra:
                src.insert(src.index("END_PRINT\n"), extra + "\n")
            with self.assertRaisesRegex(post.PostError, error):
                run(src)
            path = tempfile.mktemp(suffix=".gcode")
            with open(path, "w") as f:
                f.writelines(src)
            try:
                self.assertEqual(post.main([path]), 1)
                with open(path) as f:
                    self.assertEqual(f.readlines(), src)
            finally:
                os.unlink(path)


@unittest.skipIf(post.np is None, "needs numpy")
class Ink(unittest.TestCase):
    def test_ink_is_on_the_coloured_lines_and_off_the_edge(self):
        # Magenta filament: magenta dots only, on the coloured band (Y 95-96.6), never within the 0.5 mm edge margin
        # of the block's outline (no brim: nothing below but the block).
        out, _ = run(block_gcode(layers=4))
        header, records, dots = job_dots(out)
        self.assertTrue(dots)
        self.assertEqual({c for _, c, _, _, _, _ in dots}, {polydye.MAGENTA})
        xs, ys = [d[3] for d in dots], [d[4] for d in dots]
        self.assertGreaterEqual(min(xs), 95.5)
        self.assertLessEqual(max(xs), 104.5)
        self.assertGreaterEqual(min(ys), 95.5)
        self.assertLessEqual(max(ys), 96.61 + PITCH)
        # With a brim under it the edge is safe: the ink reaches the block's edge.
        out, _ = run(block_gcode(layers=4, brim=True))
        _, _, dots = job_dots(out)
        self.assertLess(min(d[4] for d in dots), 95.1)
        self.assertLess(min(d[3] for d in dots), 95.1)

    def test_every_fire_is_at_least_two_columns(self):
        # Whatever the registration moves (an odd number of columns too) and in both directions.
        out, _ = run(block_gcode(layers=3, band=4., config={'filament_colour': '#FFFFFF;#4060A0'}), "--edge-margin",
                     "0")
        for registration in ((0, 0, 0, 0), (-34, 1, 27, -1)):
            _, records, dots = job_dots(out, registration)
            self.assertEqual({r['dir'] for r in records}, {1, -1})
            self.assertEqual({c for _, c, _, _, _, _ in dots}, {0, 1, 2})
            self.assertGreaterEqual(min(d[5] for d in dots), 2)

    def test_coverage_follows_the_colour_and_the_ink_limit(self):
        # #FF00FF: no cyan or yellow, magenta at the ink limit: every dot by default (100 %, solid), half the dots at
        # 50 %, a quarter at 25 %.
        for limit, share in (("100", 1.), ("50", 0.5), ("25", 0.25)):
            out, _ = run(block_gcode(layers=1, band=4., top=True), "--edge-margin", "0", "--ink-limit", limit)
            _, records, dots = job_dots(out)
            # The band: 9.6 mm lines 0.4 mm apart filling 4 mm, plus the lines' half widths all round.
            area = (9.6 + 0.42) * (4. + 0.02) / (SX * PITCH)
            self.assertAlmostEqual(len(dots) / area, share, delta=0.03)

    def test_top_surfaces_get_their_coats(self):
        out, _ = run(block_gcode(layers=2, top=True), "--edge-margin", "0")
        self.assertEqual(set(int(c) for c in re.findall(r"; layer 1 pass \d+, coat (\d)", "".join(out))), {1})
        out, _ = run(block_gcode(layers=2, top=True), "--edge-margin", "0", "--top-coats", "2")
        text = "".join(out)
        self.assertEqual(set(int(c) for c in re.findall(r"; layer 1 pass \d+, coat (\d)", text)), {1, 2})
        self.assertEqual(set(int(c) for c in re.findall(r"; layer 0 pass \d+, coat (\d)", text)), {1})
        out, _ = run(block_gcode(layers=2, top=True), "--edge-margin", "0", "--top-coats", "3")
        self.assertEqual(set(int(c) for c in re.findall(r"; layer 1 pass \d+, coat (\d)", "".join(out))), {1, 2, 3})

    def test_partial_tones_are_an_ordered_dither(self):
        # #BFBFBF: a quarter of each ink. The colours fire on different cells (pairs of columns, nozzle positions),
        # each spread evenly: in every 8 x 8 block of cells, 16.
        out, _ = run(block_gcode(layers=1, band=4., config={'filament_colour': '#FFFFFF;#BFBFBF'}),
                     "--edge-margin", "0")
        _, records, dots = job_dots(out)
        cells = [set((r['n'], round((y - r['y']) / PITCH) // 2, p) for r, c, p, x, y, _ in dots if c == ch)
                 for ch in range(3)]
        self.assertTrue(all(cells))
        self.assertFalse(cells[0] & cells[1] or cells[0] & cells[2] or cells[1] & cells[2])
        # Any 8 x 8 block of a period-8 matrix has each threshold once: inside the ink, 48 cells of 64 fire, 16 each.
        blocks = {}
        for ch in range(3):
            for n, row, p in cells[ch]:
                blocks.setdefault((n, row // 8, p // 8), [0, 0, 0])[ch] += 1
        inside = [v for v in blocks.values() if sum(v) == 48]
        self.assertGreater(len(inside), 10)
        self.assertEqual({tuple(v) for v in inside}, {(16, 16, 16)})

    def test_passes_name_their_object(self):
        out, _ = run(block_gcode(layers=1, band=4.), "--edge-margin", "0")
        _, records, _ = job_dots(out)
        self.assertEqual({r['object'] for r in records}, {"cube"})
        out, _ = run(block_gcode(layers=1, band=4., obj=None), "--edge-margin", "0")
        self.assertNotIn("EXCLUDE_OBJECT", "".join(out))
        _, records, _ = job_dots(out)
        self.assertEqual({r['object'] for r in records}, {"-"})

    def test_swaths_tile_the_nozzle_grid(self):
        # Passes side by side: the next pass's first nozzle position lands one pitch past the last one's.
        out, _ = run(block_gcode(layers=1, band=4.), "--edge-margin", "0")
        _, records, _ = job_dots(out)
        xs = sorted(r['x'] for r in records)
        self.assertGreater(len(xs), 1)
        for a, b in zip(xs, xs[1:]):
            self.assertAlmostEqual((b - a) / SX, 68., places=2)


@unittest.skipIf(post.np is None, "needs numpy")
class Timing(unittest.TestCase):
    def times(self, moves, dwells=(), accel=1000., scv=5., vmax=500.):
        timing = {'moves': [(n,) + m for n, m in enumerate(moves)], 'dwells': list(dwells)}
        return post.line_times(len(moves) + 1, timing, accel, scv, vmax)

    def test_moves_are_planned_like_klipper(self):
        # 100 mm at 100 mm/s, 1000 mm/s^2, from and to a stop: 0.1 s each way to and from speed (10 mm), 0.9 s at it.
        move = (100., 0., 0., 0., 100., None, None, False)
        self.assertAlmostEqual(sum(self.times([move])), 1.1)
        # In two straight halves it's the same; turning back halfway stops in the middle.
        half = (50., 0., 0., 0., 100., None, None, False)
        self.assertAlmostEqual(sum(self.times([half, half])), 1.1)
        self.assertAlmostEqual(sum(self.times([half, (-50., 0., 0., 0., 100., None, None, False)])), 1.2)
        # A right angle slows to the square corner velocity's junction speed: between the two.
        corner = sum(self.times([half, (0., 50., 0., 0., 100., None, None, False)]))
        self.assertTrue(1.1 < corner < 1.2, corner)
        # The G-code's accel, max_velocity, an extrude-only move and a dwell.
        self.assertAlmostEqual(sum(self.times([(100., 0., 0., 0., 100., 4000., None, False)])), 1.025)
        self.assertAlmostEqual(sum(self.times([move], vmax=50.)), 2.05)
        self.assertAlmostEqual(sum(self.times([(0., 0., 0., -.8, 35., None, None, False)], [(1, 2.)])), .8 / 35 + 2.)

    def test_the_estimate_matches_orcas_for_its_own_gcode(self):
        # The block at 50 mm/s: Orca's lines, planned here, about as long as the moves at full speed and no more than
        # the stops at every line would take.
        src = block_gcode(layers=2, feed=3000)
        layers, config, _, _, _, timing = post.parse(src)
        total = sum(post.line_times(len(src), timing, 3000., 5., 500.))
        length = sum(abs(dx) + abs(dy) for _, dx, dy, _, _, _, _, _, _ in timing['moves'])
        self.assertTrue(length / 50. < total < length / 50. + len(timing['moves']) * 2 * 50. / 3000., total)


@unittest.skipIf(post.np is None, "needs numpy")
class WarmAndPrime(unittest.TestCase):
    """POLYDYE_PREWARM during each ink layer's last seconds of plastic, POLYDYE_PRIME when a colour has been idle."""

    def test_the_burst_ends_as_the_ink_starts(self):
        # Layers of about 20 s (lines at 10 mm/s): the burst goes where the layer has its length less the lead to the
        # first pass to go (5 s), or 6 s when a prime comes first (its spit would cut a burst still firing).
        out, summary = run(block_gcode(layers=3, feed=600))
        text = "".join(out)
        prewarms = [(n, ln) for n, ln in enumerate(out) if ln.startswith("POLYDYE_PREWARM")]
        inks = [n for n, ln in enumerate(out) if ln.startswith("; PolyDye ink: layer")]
        self.assertEqual((len(prewarms), len(inks)), (3, 3))
        self.assertIn("3 prewarm bursts, 1 primes", summary)
        for k, ((n, line), ink) in enumerate(zip(prewarms, inks)):
            self.assertTrue((inks[k - 1] if k else 0) < n < ink, (k, n, ink))
            m = re.match(r"POLYDYE_PREWARM SECONDS=6 ; warms the head for layer (\d+)'s ink: ([\d.]+) s of moves to go",
                         line)
            self.assertEqual(int(m.group(1)), k)
            # A line is about 1 s.
            to_go = 6. if k == 0 else 5.
            self.assertTrue(to_go <= float(m.group(2)) < to_go + 1.1, line)
        self.assertEqual(re.findall(r"POLYDYE_PRIME", text), ["POLYDYE_PRIME"])

    def test_short_layers_warm_through(self):
        # Layers of about 1 s: the burst starts right after the previous layer's ink (or at the first layer).
        out, _ = run(block_gcode(layers=3))
        for k in range(3):
            n = next(n for n, ln in enumerate(out) if ln.startswith("POLYDYE_PREWARM") and "layer %d's" % (k,) in ln)
            if k == 0:
                self.assertEqual(out[n + 1], ";LAYER_CHANGE\n")
            else:  # the end of the previous layer's ink
                self.assertEqual(out[n - 1], "EXCLUDE_OBJECT_START NAME=cube\n")

    def test_a_colour_idle_too_long_primes_again(self):
        src = block_gcode(layers=3, feed=600)
        # About 20 s between layers' ink: with --prime-idle 10 every layer primes, with 90 only the first.
        out, summary = run(src, "--prime-idle", "10")
        self.assertEqual("".join(out).count("POLYDYE_PRIME ;"), 3)
        self.assertIn("3 primes", summary)
        # Magenta from layer 6 on, after about 2 min of white: the first ink layer primes, and so would a later one
        # whose colour had been idle that long.
        out, _ = run(block_gcode(layers=8, feed=600, colour_from=6))
        text = "".join(out)
        self.assertEqual(re.findall(r"; PolyDye ink: layer (\d+)", text), ["6", "7"])
        self.assertEqual(text.split("; PolyDye ink: layer 7")[0].count("POLYDYE_PRIME ;"), 1)
        self.assertEqual(text.count("POLYDYE_PRIME ;"), 1)
        # Accelerations and speeds of 0 in the profile (Orca's "off") fall back to the defaults.
        out, summary = run(block_gcode(layers=3, feed=600, config={'default_acceleration': '0',
                                                                    'machine_max_speed_x': '0,0'}) +
                           ["SET_VELOCITY_LIMIT ACCEL=0\n", "M204 S0\n"])
        self.assertIn("3 prewarm bursts, 1 primes", summary)
        # Off: neither.
        out, summary = run(src, "--prime-idle", "0", "--prewarm", "0")
        self.assertNotIn("POLYDYE_PRIME", "".join(out))
        self.assertNotIn("POLYDYE_PREWARM", "".join(out))
        self.assertIn("0 prewarm bursts, 0 primes", summary)


@unittest.skipIf(post.np is None, "needs numpy")
class Decap(unittest.TestCase):
    def test_a_colour_is_idle_from_its_own_last_pass(self):
        # Layer 0: a short cyan pass, then 120 s of magenta passes; layer 1, 2 s of moves later: cyan again. Cyan
        # last ejected at its own pass, over 90 s before, so layer 1 primes; magenta's ink 2 s ago doesn't count.
        opts = post.options(["--dry", "5", "x.gcode"])
        pitch = 25.4 / opts.dpi

        def ink(colours, seconds):
            columns = int(round((seconds - 60. / opts.travel) * opts.pass_speed / pitch)) - int(2 * 3. / pitch)
            return post.InkPass(0, 1, None, 100., 100., columns, colours, b"")

        layers = []
        for n, (start, last) in enumerate(((0, 1), (2, 3))):
            layer = post.Layer(n)
            layer.start_line, layer.last_line = start, last
            layers.append(layer)
        timing = {'moves': [], 'dwells': [(1, 1.), (3, 1.)]}
        plan = [(layers[0], [ink('c', 5.)] + [ink('m', 40.) for _ in range(3)]), (layers[1], [ink('c', 5.)])]
        before, primes = post.warm_and_prime(["G4\n"] * 5, layers, plan, {}, timing, opts)
        self.assertEqual(primes, {0, 1})
        # Magenta's passes last: it's fresh, so a magenta layer after it doesn't prime.
        plan[1] = (layers[1], [ink('m', 5.)])
